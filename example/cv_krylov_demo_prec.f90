!*****************************************************************************************
    program cv_krylov_demo_prec

    use fvode
    use fvode_linsol_spgmr, only: sun_linsol_spgmr
    use cv_krylov_demo_prec_module

    implicit none

    real(wp),parameter :: T0        = 0.0_wp     !! initial time
    real(wp),parameter :: RTOL      = 1.0e-5_wp  !! scalar relative tolerance
    real(wp),parameter :: ATOL      = 1.0e-5_wp  !! scalar absolute tolerance
    integer,parameter  :: MAXL      = 0          !! maximum Krylov dimension (0: default, 5)
    real(wp),parameter :: DELTA     = 0.0_wp     !! linear tolerance factor (0: default, 0.05)
    real(wp),parameter :: T1        = 1.0e-8_wp  !! first output time
    real(wp),parameter :: TOUT_MULT = 10.0_wp    !! output time factor (up to t = 1)
    real(wp),parameter :: DTOUT     = 1.0_wp     !! output time increment (after t = 1)
    integer,parameter  :: NOUT      = 18         !! number of output times
    real(wp),parameter :: AA = 1.0_wp, EE = 1.0e4_wp, GG = 0.5e-6_wp, BB = 1.0_wp  !! printed problem parameters a, e, g, b
    real(wp),parameter :: DPREY = 1.0_wp, DPRED = 0.5_wp, ALPHA = 1.0_wp  !! printed diffusion coefficients and rate parameter

    type(web_solver) :: cvode  !! the CVODE solver with the problem data
    real(wp),dimension(NEQ) :: c  !! the concentrations
    real(wp) :: t, tout  !! current and output times
    logical :: firstrun  !! is this the first of the four runs?
    integer :: jpre, gstype, retval, iout  !! preconditioner type, Gram-Schmidt type, return flag and output counter

    call init_user_data(cvode)

    ! print problem description
    call print_intro()

    ! loop over jpre and gstype (four cases)
    do jpre = SUN_PREC_LEFT, SUN_PREC_RIGHT
        do gstype = SUN_MODIFIED_GS, SUN_CLASSICAL_GS

            ! initialize c and print heading
            call cinit(c, cvode)
            call print_header(jpre, gstype)

            ! call CVodeInit or CVodeReInit, then SPGMR to set up problem
            firstrun = (jpre == SUN_PREC_LEFT) .and. (gstype == SUN_MODIFIED_GS)
            if (firstrun) then
                call cvode%create(CV_BDF, retval)
                call cvode%init(f, T0, c, retval)
                call cvode%ss_tolerances(RTOL, ATOL, retval)
                call cvode%set_linear_solver(sun_linsol_spgmr(NEQ, jpre, MAXL), flag=retval)
                if (check_retval(retval, 'CVodeSetLinearSolver')) stop 1
                select type (LS => cvode%LS)
                type is (sun_linsol_spgmr)
                    retval = LS%set_gs_type(gstype)
                end select
                if (check_retval(retval, 'SUNLinSol_SPGMRSetGSType')) stop 1
                call cvode%set_eps_lin(DELTA, retval)
                if (check_retval(retval, 'CVodeSetEpsLin')) stop 1
                call cvode%set_preconditioner(precond, psolve, retval)
                if (check_retval(retval, 'CVodeSetPreconditioner')) stop 1
            else
                call cvode%reinit(T0, c, retval)
                if (check_retval(retval, 'CVodeReInit')) stop 1
                select type (LS => cvode%LS)
                type is (sun_linsol_spgmr)
                    retval = LS%set_prec_type(jpre)
                    if (check_retval(retval, 'SUNLinSol_SPGMRSetPrecType')) stop 1
                    retval = LS%set_gs_type(gstype)
                end select
                if (check_retval(retval, 'SUNLinSol_SPGMRSetGSType')) stop 1
            end if

            ! print initial values
            if (firstrun) call print_all_species(c, T0)

            ! loop over output points, call CVode, print sample solution values
            tout = T1
            do iout = 1, NOUT
                call cvode%solve(tout, c, t, CV_NORMAL, retval)
                call print_output(t)
                if (firstrun .and. mod(iout, 3) == 0) call print_all_species(c, t)
                if (check_retval(retval, 'CVode')) exit
                if (tout > 0.9_wp) then
                    tout = tout + DTOUT
                else
                    tout = tout * TOUT_MULT
                end if
            end do

            ! print final statistics, and loop for next case
            call print_final_stats()

        end do
    end do

    call cvode%destroy()

    contains

        function cg(x, p) result(s)
        !! a real formatted like C's `%.<p>g`: p significant digits, fixed
        !! notation if the decimal exponent is in [-4, p), otherwise
        !! exponential notation, trailing zeros removed
        real(wp),intent(in) :: x  !! value to format
        integer,intent(in) :: p  !! number of significant digits
        character(len=:),allocatable :: s  !! formatted value
        character(len=64) :: buf  !! write buffer
        character(len=16) :: fmt  !! run-time format
        integer :: ie  !! position of the exponent letter in buf
        integer :: iexp  !! decimal exponent (after rounding to p digits)
        if (x == 0.0_wp) then
            s = '0'
            return
        end if
        write(fmt, '(a,i0,a,i0,a)') '(es', p + 10, '.', p - 1, 'e3)'
        write(buf, fmt) x
        buf = adjustl(buf)
        ie = index(buf, 'E')
        read(buf(ie+1:), *) iexp
        if (iexp < -4 .or. iexp >= p) then
            s = strip_zeros(buf(1:ie-1))
            write(buf, '(a,"e",sp,i0.2)') s, iexp
            s = trim(buf)
        else
            write(fmt, '(a,i0,a)') '(f0.', p - 1 - iexp, ')'
            write(buf, fmt) x
            buf = adjustl(buf)
            if (buf(1:1) == '.') buf = '0'//buf
            if (buf(1:2) == '-.') buf = '-0'//buf(2:)
            s = strip_zeros(trim(buf))
        end if
        end function cg

        function strip_zeros(str) result(s)
        !! remove trailing zeros after a decimal point (and the point itself)
        character(len=*),intent(in) :: str  !! the number
        character(len=:),allocatable :: s  !! the number without trailing zeros
        integer :: n  !! length of the result
        s = trim(str)
        if (index(s, '.') == 0) return
        n = len(s)
        do while (s(n:n) == '0')
            n = n - 1
        end do
        if (s(n:n) == '.') n = n - 1
        s = s(1:n)
        end function strip_zeros

        subroutine print_intro()
        !! print the problem description
        write(*,'(//a//)') 'Demonstration program for CVODE - SPGMR linear solver'
        write(*,'(a,i0)') 'Food web problem with ns species, ns = ', NS
        write(*,'(a/)') 'Predator-prey interaction and diffusion on a 2-D square'
        write(*,'(6a)') 'Matrix parameters: a = ', cg(AA, 2), '   e = ', cg(EE, 2), '   g = ', cg(GG, 2)
        write(*,'(2a)') 'b parameter = ', cg(BB, 2)
        write(*,'(4a)') 'Diffusion coefficients: Dprey = ', cg(DPREY, 2), '   Dpred = ', cg(DPRED, 2)
        write(*,'(2a/)') 'Rate parameter alpha = ', cg(ALPHA, 2)
        write(*,'(a,i0,a,i0,a,i0,a/)') 'Mesh dimensions (mx,my) are ', MX, ', ', MY, &
            '.  Total system size is neq = ', NEQ, ' '
        write(*,'(5a/)') 'Tolerances: reltol = ', cg(RTOL, 2), ', abstol = ', cg(ATOL, 2), ' '
        write(*,'(a)') 'Preconditioning uses a product of:'
        write(*,'(a,i0,a)') '  (1) Gauss-Seidel iterations with itmax = ', ITMAX, ' iterations, and'
        write(*,'(a)') '  (2) interaction-only block-diagonal matrix with block-grouping'
        write(*,'(a,i0,a,i0,a,i0,a)') '  Number of diagonal block groups = ngrp = ', NGRP, &
            '  (ngx by ngy, ngx = ', NGX, ', ngy = ', NGY, ')'
        write(*,'(//a)') repeat('-', 76)
        end subroutine print_intro

        subroutine print_header(jpre, gstype)
        !! print the heading of a run
        integer,intent(in) :: jpre  !! preconditioner type
        integer,intent(in) :: gstype  !! Gram-Schmidt type
        if (jpre == SUN_PREC_LEFT) then
            write(*,'(//a)') 'Preconditioner type is           jpre = SUN_PREC_LEFT'
        else
            write(*,'(//a)') 'Preconditioner type is           jpre = SUN_PREC_RIGHT'
        end if
        if (gstype == SUN_MODIFIED_GS) then
            write(*,'(/a//)') 'Gram-Schmidt method type is    gstype = SUN_MODIFIED_GS'
        else
            write(*,'(/a//)') 'Gram-Schmidt method type is    gstype = SUN_CLASSICAL_GS'
        end if
        end subroutine print_header

        subroutine print_all_species(c, t)
        !! print the concentrations of all species on the mesh
        real(wp),dimension(0:),intent(in) :: c  !! the concentrations
        real(wp),intent(in) :: t  !! current time
        integer :: i, jx, jy  !! species and mesh indices
        character(len=10) :: field  !! a value, left-justified in 10 characters (C: %-10.6g)
        write(*,'(3a/)') 'c values at t = ', cg(t, 6), ':'
        do i = 1, NS
            write(*,'(a,i0)') 'Species ', i
            do jy = MY - 1, 0, -1
                do jx = 0, MX - 1
                    field = cg(c((i - 1) + jx * NS + jy * MXNS), 6)
                    write(*,'(a)',advance='no') field
                end do
                write(*,'(a)') ''
            end do
            write(*,'(a)') ''
        end do
        end subroutine print_all_species

        subroutine print_output(t)
        !! print the step statistics at an output time
        real(wp),intent(in) :: t  !! current time
        write(*,'(a,es10.2,a,i0,a,i0,a,i0,a,i0,a,es11.2/)') 't = ', t, '  nst = ', cvode%get_num_steps(), &
            '  nfe = ', cvode%get_num_rhs_evals(), '  nni = ', cvode%get_num_nonlin_solv_iters(), &
            '  qu = ', cvode%get_last_order(), '  hu = ', cvode%get_last_step()
        end subroutine print_output

        subroutine print_final_stats()
        !! print the final statistics (except the workspace sizes)
        integer(li) :: nfe, nfeLS, nni, nli  !! f evaluations (integrator, linear solver), nonlinear and linear iterations
        real(wp) :: avdim  !! average Krylov subspace dimension
        nfe   = cvode%get_num_rhs_evals()
        nfeLS = cvode%get_num_lin_rhs_evals()
        nni   = cvode%get_num_nonlin_solv_iters()
        nli   = cvode%get_num_lin_iters()
        write(*,'(//a/)') ' Final statistics for this run:'
        write(*,'(a,i4,a)') ' Number of steps                       = ', cvode%get_num_steps(), ' '
        write(*,'(a,i4,a)') ' Number of f-s                         = ', nfe, ' '
        write(*,'(a,i4,a)') ' Number of f-s (SPGMR)                 = ', nfeLS, ' '
        write(*,'(a,i4,a)') ' Number of f-s (TOTAL)                 = ', nfe + nfeLS, ' '
        write(*,'(a,i4,a)') ' Number of setups                      = ', cvode%get_num_lin_solv_setups(), ' '
        write(*,'(a,i4,a)') ' Number of nonlinear iterations        = ', nni, ' '
        write(*,'(a,i4,a)') ' Number of linear iterations           = ', nli, ' '
        write(*,'(a,i4,a)') ' Number of preconditioner evaluations  = ', cvode%get_num_prec_evals(), ' '
        write(*,'(a,i4,a)') ' Number of preconditioner solves       = ', cvode%get_num_prec_solves(), ' '
        write(*,'(a,i4,a)') ' Number of error test failures         = ', cvode%get_num_err_test_fails(), ' '
        write(*,'(a,i4,a)') ' Number of nonlinear conv. failures    = ', &
            cvode%get_num_nonlin_solv_conv_fails(), ' '
        write(*,'(a,i4,a)') ' Number of linear convergence failures = ', cvode%get_num_lin_conv_fails(), ' '
        avdim = 0.0_wp
        if (nni > 0) avdim = real(nli, wp) / real(nni, wp)
        write(*,'(a,f0.3,a)') ' Average Krylov subspace dimension     = ', avdim, ' '
        write(*,'(//a)') repeat('-', 76)
        write(*,'(a)') repeat('-', 76)
        end subroutine print_final_stats

        logical function check_retval(retval, funcname)
        !! report a negative return flag (C: `check_retval(&retval, funcname, 1)`)
        integer,intent(in) :: retval  !! the return flag
        character(len=*),intent(in) :: funcname  !! name of the called function
        check_retval = retval < 0
        if (check_retval) write(*,'(/3a,i0/)') 'SUNDIALS_ERROR: ', funcname, '() failed with retval = ', retval
        end function check_retval

    end program cv_krylov_demo_prec
