!*****************************************************************************************
!>
!  Food web (predator-prey with diffusion) problem in 2-D, BDF + Newton +
!  SPGMR with a user-supplied preconditioner that is the product of
!  Gauss-Seidel iterations (for the diffusion part of the Jacobian) and an
!  interaction-only block-diagonal matrix with block grouping. It is solved
!  four times: left and right preconditioning, each with modified and
!  classical Gram-Schmidt.
!
!  FVODE port of the SUNDIALS example `examples/cvode/serial/cvKrylovDemo_prec.c`
!  (same problem, settings and output, except the workspace sizes; compare
!  with `cvKrylovDemo_prec.out`).
!
!  The problem has `ns = 2*np` species: np prey and np predators,
!
!      dc(i)/dt = d(i)*(c(i)_xx + c(i)_yy) + f_i(x,y,c),   i = 1,...,ns,
!      f_i(x,y,c) = c(i)*(b(i) + sum_j a(i,j)*c(j)),
!
!  on the unit square with homogeneous Neumann boundary conditions, with
!  np = 3 on a 6 x 6 mesh (216 equations). The preconditioner blocks are
!  generated by difference quotients, one block per group of mesh points.

    module cv_krylov_demo_prec_module

    use fvode
    use fvode_core, only: cvode_solver
    use fvode_linsol_direct, only: dense_getrf, dense_getrs
    use fvode_nvector, only: n_vwrmsnorm

    implicit none

    private

    real(wp),parameter :: AA    = 1.0_wp     !! a: interaction coefficient
    real(wp),parameter :: EE    = 1.0e4_wp   !! e: predator-prey interaction coefficient
    real(wp),parameter :: GG    = 0.5e-6_wp  !! g: prey-predator interaction coefficient
    real(wp),parameter :: BB    = 1.0_wp     !! b: growth coefficient
    real(wp),parameter :: DPREY = 1.0_wp     !! diffusion coefficient of the prey
    real(wp),parameter :: DPRED = 0.5_wp     !! diffusion coefficient of the predators
    real(wp),parameter :: ALPHA = 1.0_wp     !! rate parameter alpha
    integer,parameter,public :: NP = 3       !! number of prey (and of predators)
    integer,parameter,public :: NS = 2 * NP  !! number of species
    integer,parameter,public :: MX = 6       !! number of mesh points in x
    integer,parameter,public :: MY = 6       !! number of mesh points in y
    integer,parameter,public :: MXNS = MX * NS  !! number of unknowns in a mesh row
    real(wp),parameter :: AX = 1.0_wp        !! length of the domain in x
    real(wp),parameter :: AY = 1.0_wp        !! length of the domain in y
    real(wp),parameter :: DX = AX / real(MX - 1, wp)  !! mesh spacing in x
    real(wp),parameter :: DY = AY / real(MY - 1, wp)  !! mesh spacing in y
    integer,parameter :: MP = NS             !! size of the preconditioner blocks
    integer,parameter :: MQ = MX * MY        !! number of mesh points
    integer,parameter :: MXMP = MX * MP      !! number of unknowns in a mesh row (blocks)
    integer,parameter,public :: NGX = 2      !! number of block groups in x
    integer,parameter,public :: NGY = 2      !! number of block groups in y
    integer,parameter,public :: NGRP = NGX * NGY  !! number of block groups
    integer,parameter,public :: ITMAX = 5    !! number of Gauss-Seidel iterations
    integer,parameter,public :: NEQ = NS * MX * MY  !! number of equations

    type,extends(cvode_solver),public :: web_solver
        !! the CVODE solver plus the problem data (C: WebData)
        real(wp),dimension(MP,MP,0:NGRP-1) :: P = 0.0_wp  !! the preconditioner blocks (LU factors), one per group
        integer(ip),dimension(MP,0:NGRP-1) :: pivot = 0  !! pivots of the LU factors of the blocks
        integer :: ns = NS  !! number of species
        integer :: mxns = MXNS  !! number of unknowns in a mesh row
        integer,dimension(0:NGX) :: jgx = 0  !! group boundaries in x
        integer,dimension(0:NGY) :: jgy = 0  !! group boundaries in y
        integer,dimension(0:MX-1) :: jigx = 0  !! group index of each x mesh index
        integer,dimension(0:MY-1) :: jigy = 0  !! group index of each y mesh index
        integer,dimension(0:NGX-1) :: jxr = 0  !! representative x mesh index of each group
        integer,dimension(0:NGY-1) :: jyr = 0  !! representative y mesh index of each group
        real(wp),dimension(0:NS-1,0:NS-1) :: acoef = 0.0_wp  !! interaction coefficients a(i,j)
        real(wp),dimension(0:NS-1) :: bcoef = 0.0_wp  !! growth coefficients b(i)
        real(wp),dimension(0:NS-1) :: diff = 0.0_wp  !! diffusion coefficients d(i)
        real(wp),dimension(0:NS-1) :: cox = 0.0_wp  !! d(i)/dx**2
        real(wp),dimension(0:NS-1) :: coy = 0.0_wp  !! d(i)/dy**2
        real(wp) :: dx = 0.0_wp  !! mesh spacing in x
        real(wp) :: dy = 0.0_wp  !! mesh spacing in y
        real(wp) :: srur = 0.0_wp  !! sqrt(unit roundoff)
        real(wp),dimension(0:NEQ-1) :: fsave = 0.0_wp  !! the interaction rates saved by f (for the preconditioner)
        real(wp),dimension(0:NEQ-1) :: tmp = 0.0_wp  !! work vector
        real(wp),dimension(0:NEQ-1) :: rewt = 0.0_wp  !! the error weights
        real(wp),dimension(0:NEQ-1) :: cwork = 0.0_wp  !! perturbed copy of c (C perturbs c in place)
    end type web_solver

    public :: f, precond, psolve, init_user_data, cinit

    contains

    subroutine init_user_data(w)
    !! load the problem constants (C: `InitUserData`)
    type(web_solver),intent(inout) :: w  !! the solver with the problem data
    integer :: i, j  !! species indices
    w%acoef = 0.0_wp
    do j = 0, NP - 1
        do i = 0, NP - 1
            w%acoef(NP + i, j) = EE
            w%acoef(i, NP + j) = -GG
        end do
        w%acoef(j, j)           = -AA
        w%acoef(NP + j, NP + j) = -AA
        w%bcoef(j)      = BB
        w%bcoef(NP + j) = -BB
        w%diff(j)       = DPREY
        w%diff(NP + j)  = DPRED
    end do

    ! set remaining problem parameters
    w%mxns = MXNS
    w%dx = DX
    w%dy = DY
    do i = 0, NS - 1
        w%cox(i) = w%diff(i) / DX**2
        w%coy(i) = w%diff(i) / DY**2
    end do

    ! set remaining method parameters
    w%srur = sqrt(SUN_UNIT_ROUNDOFF)
    call set_groups(MX, NGX, w%jgx, w%jigx, w%jxr)
    call set_groups(MY, NGY, w%jgy, w%jigy, w%jyr)
    end subroutine init_user_data

    subroutine set_groups(m, ng, jg, jig, jr)
    !! a uniform partition of (0,1,...,m-1) into ng groups (C: `SetGroups`):
    !! group ig has the indices jg(ig),...,jg(ig+1)-1, index j is in group
    !! jig(j), and the group ig is represented by the index jr(ig)
    integer,intent(in) :: m  !! number of indices
    integer,intent(in) :: ng  !! number of groups
    integer,dimension(0:),intent(out) :: jg  !! group boundaries, 0:ng
    integer,dimension(0:),intent(out) :: jig  !! group of each index, 0:m-1
    integer,dimension(0:),intent(out) :: jr  !! representative index of each group, 0:ng-1
    integer :: ig, j, len1, mper, ngm1  !! group and node indices, number of nodes in the first ng-1 groups, nodes per group, ng-1
    mper = m / ng
    do ig = 0, ng - 1
        jg(ig) = ig * mper
    end do
    jg(ng) = m
    ngm1 = ng - 1
    len1 = ngm1 * mper
    do j = 0, len1 - 1
        jig(j) = j / mper
    end do
    do j = len1, m - 1
        jig(j) = ngm1
    end do
    do ig = 0, ngm1 - 1
        jr(ig) = ((2 * ig + 1) * mper - 1) / 2
    end do
    jr(ngm1) = (ngm1 * mper + m - 1) / 2
    end subroutine set_groups

    subroutine cinit(c, w)
    !! the initial values (C: `CInit`)
    real(wp),dimension(0:),intent(out) :: c  !! the solution vector
    type(web_solver),intent(in) :: w  !! the solver with the problem data
    integer :: jx, jy, ioff, iyoff, i, ici  !! mesh and species indices and offsets
    real(wp) :: argx, argy, x, y, x_factor, y_factor  !! profile factors and mesh coordinates
    x_factor = 4.0_wp / AX**2
    y_factor = 4.0_wp / AY**2
    do jy = 0, MY - 1
        y     = jy * w%dy
        argy  = (y_factor * y * (AY - y))**2
        iyoff = w%mxns * jy
        do jx = 0, MX - 1
            x    = jx * w%dx
            argx = (x_factor * x * (AX - x))**2
            ioff = iyoff + w%ns * jx
            do i = 1, w%ns
                ici = ioff + i - 1
                c(ici) = 10.0_wp + i * argx * argy
            end do
        end do
    end do
    end subroutine cinit

    function f(me, t, y, ydot) result(retval)
    !! right-hand side: the interaction rates (saved in `fsave`) plus diffusion
    class(cvode_solver),intent(inout) :: me  !! the CVODE solver (gives access to problem data)
    real(wp),intent(in) :: t  !! current time
    real(wp),dimension(0:),intent(in) :: y  !! the concentrations c
    real(wp),dimension(0:),intent(out) :: ydot  !! dc/dt
    integer :: retval  !! 0 on success
    integer :: i, ic, ici, idxl, idxu, jx, jy, iyoff, idyu, idyl  !! species and mesh indices, offsets of the neighbors
    real(wp) :: dcxli, dcxui, dcyli, dcyui, x, yy  !! differences to the neighbors and the mesh coordinates
    select type (me)
    class is (web_solver)
        do jy = 0, MY - 1
            yy    = jy * me%dy
            iyoff = me%mxns * jy
            idyu  = me%mxns; if (jy == MY - 1) idyu = -me%mxns
            idyl  = me%mxns; if (jy == 0) idyl = -me%mxns
            do jx = 0, MX - 1
                x  = jx * me%dx
                ic = iyoff + me%ns * jx
                ! get interaction rates at one point (x,y)
                call web_rates(me, x, yy, t, y(ic:ic+NS-1), me%fsave(ic:ic+NS-1))
                idxu = me%ns; if (jx == MX - 1) idxu = -me%ns
                idxl = me%ns; if (jx == 0) idxl = -me%ns
                do i = 1, me%ns
                    ici = ic + i - 1
                    ! do differencing in y
                    dcyli = y(ici) - y(ici - idyl)
                    dcyui = y(ici + idyu) - y(ici)
                    ! do differencing in x
                    dcxli = y(ici) - y(ici - idxl)
                    dcxui = y(ici + idxu) - y(ici)
                    ! collect terms and load cdot elements
                    ydot(ici) = me%coy(i - 1) * (dcyui - dcyli) + &
                                me%cox(i - 1) * (dcxui - dcxli) + me%fsave(ici)
                end do
            end do
        end do
    end select
    retval = 0
    end function f

    subroutine web_rates(w, x, y, t, c, rate)
    !! the interaction rates of the species at one mesh point (C: `WebRates`)
    type(web_solver),intent(in) :: w  !! the solver with the problem data
    real(wp),intent(in) :: x  !! x coordinate
    real(wp),intent(in) :: y  !! y coordinate
    real(wp),intent(in) :: t  !! current time
    real(wp),dimension(0:),intent(in) :: c  !! concentrations at the point
    real(wp),dimension(0:),intent(out) :: rate  !! interaction rates at the point
    integer :: i, j  !! species indices
    real(wp) :: fac  !! 1 + alpha*x*y
    rate(0:NS-1) = 0.0_wp
    do j = 0, NS - 1
        do i = 0, NS - 1
            rate(i) = rate(i) + c(j) * w%acoef(i, j)
        end do
    end do
    fac = 1.0_wp + ALPHA * x * y
    do i = 0, NS - 1
        rate(i) = c(i) * (w%bcoef(i) * fac + rate(i))
    end do
    end subroutine web_rates

    function precond(me, t, y, fy, jok, jcur, gamma) result(retval)
    !! preconditioner setup: difference-quotient interaction-only Jacobian
    !! blocks (one per group), `I - gamma*J` and its LU factors
    class(cvode_solver),intent(inout) :: me  !! the CVODE solver (gives access to problem data)
    real(wp),intent(in) :: t  !! current time
    real(wp),dimension(0:),intent(in) :: y  !! the concentrations c
    real(wp),dimension(0:),intent(in) :: fy  !! f(t, c)
    logical,intent(in) :: jok  !! may saved Jacobian data be reused? (not used: always recomputed)
    logical,intent(out) :: jcur  !! was the Jacobian data recomputed?
    real(wp),intent(in) :: gamma  !! the scalar gamma in P = I - gamma*J
    integer :: retval  !! 0 on success, 1 if a block is singular
    integer :: i, if0, if00, ig, igx, igy, j, jj, jx, jy  !! block, column, group and mesh indices
    real(wp) :: fac, r, r0, save  !! scale factor, increment, minimum increment factor, saved component
    retval = 0
    select type (me)
    class is (web_solver)
        call me%get_err_weights(me%rewt)

        ! (C perturbs c in place and restores it; here a copy is perturbed)
        me%cwork = y

        ! make mp calls to fblock to approximate each diagonal block of the
        ! Jacobian; fsave contains the base value of the rate vector and r0
        ! is a minimum increment factor for the difference quotient
        fac = n_vwrmsnorm(fy, me%rewt)
        r0  = 1000.0_wp * abs(gamma) * SUN_UNIT_ROUNDOFF * NEQ * fac
        if (r0 == 0.0_wp) r0 = 1.0_wp

        do igy = 0, NGY - 1
            jy   = me%jyr(igy)
            if00 = jy * MXMP
            do igx = 0, NGX - 1
                jx  = me%jxr(igx)
                if0 = if00 + jx * MP
                ig  = igx + igy * NGX
                ! generate ig-th diagonal block
                do j = 0, MP - 1
                    ! generate the jth column as a difference quotient
                    jj   = if0 + j
                    save = me%cwork(jj)
                    r    = max(me%srur * abs(save), r0 / me%rewt(jj))
                    me%cwork(jj) = me%cwork(jj) + r
                    fac = -gamma / r
                    call fblock(me, t, me%cwork, jx, jy, me%tmp)
                    do i = 0, MP - 1
                        me%P(i+1, j+1, ig) = (me%tmp(i) - me%fsave(if0 + i)) * fac
                    end do
                    me%cwork(jj) = save
                end do
            end do
        end do

        ! add identity matrix and do LU decompositions on blocks
        do ig = 0, NGRP - 1
            do i = 1, MP
                me%P(i, i, ig) = me%P(i, i, ig) + 1.0_wp
            end do
            if (dense_getrf(me%P(:,:,ig), me%pivot(:,ig)) /= 0) then
                retval = 1
                return
            end if
        end do

        jcur = .true.
    end select
    end function precond

    subroutine fblock(w, t, c, jx, jy, cdot)
    !! the interaction rates of block (jx,jy) (C: `fblock`)
    type(web_solver),intent(in) :: w  !! the solver with the problem data
    real(wp),intent(in) :: t  !! current time
    real(wp),dimension(0:),intent(in) :: c  !! the concentrations
    integer,intent(in) :: jx  !! mesh index in x
    integer,intent(in) :: jy  !! mesh index in y
    real(wp),dimension(0:),intent(out) :: cdot  !! the rates of the block (first ns elements)
    integer :: iblok, ic  !! block index and its offset
    real(wp) :: x, y  !! mesh coordinates
    iblok = jx + jy * MX
    y  = jy * w%dy
    x  = jx * w%dx
    ic = w%ns * iblok
    call web_rates(w, x, y, t, c(ic:ic+NS-1), cdot(0:NS-1))
    end subroutine fblock

    function psolve(me, t, y, fy, r, z, gamma, delta, lr) result(retval)
    !! preconditioner solve: Gauss-Seidel for the diffusion part, then the
    !! block-diagonal interaction part with the LU factors from [[precond]]
    class(cvode_solver),intent(inout) :: me  !! the CVODE solver (gives access to problem data)
    real(wp),intent(in) :: t  !! current time
    real(wp),dimension(:),intent(in) :: y  !! current solution
    real(wp),dimension(:),intent(in) :: fy  !! f(t, y)
    real(wp),dimension(:),intent(in) :: r  !! the right-hand side
    real(wp),dimension(:),intent(out) :: z  !! the solution
    real(wp),intent(in) :: gamma  !! the scalar gamma in P = I - gamma*J
    real(wp),intent(in) :: delta  !! tolerance (not used)
    integer,intent(in) :: lr  !! left or right preconditioner (not used)
    integer :: retval  !! 0 on success
    integer :: jx, jy, igx, igy, iv, ig  !! mesh and group indices, offset in z
    select type (me)
    class is (web_solver)
        z = r

        ! call gs_iter for Gauss-Seidel iterations
        call gs_iter(me, gamma, z, me%tmp)

        ! do backsolves for inverse of block-diagonal preconditioner factor
        iv = 1
        do jy = 0, MY - 1
            igy = me%jigy(jy)
            do jx = 0, MX - 1
                igx = me%jigx(jx)
                ig  = igx + igy * NGX
                call dense_getrs(me%P(:,:,ig), me%pivot(:,ig), z(iv:iv+MP-1))
                iv = iv + MP
            end do
        end do
    end select
    retval = 0
    end function psolve

    subroutine gs_iter(w, gamma, z, x)
    !! ITMAX Gauss-Seidel iterations for an approximation to `P^{-1} z`,
    !! where `P = I - gamma*Jd` and Jd is the diffusion part of the Jacobian
    !! (C: `GSIter`); the result is returned in z, x is a work vector
    type(web_solver),intent(in) :: w  !! the solver with the problem data
    real(wp),intent(in) :: gamma  !! the scalar gamma
    real(wp),dimension(0:),intent(inout) :: z  !! on input the right-hand side, on output the result
    real(wp),dimension(0:),intent(inout) :: x  !! work vector
    real(wp),dimension(0:NS-1) :: beta, beta2, cof1, gam, gam2  !! the coefficients of P = D - L - U
    real(wp) :: temp  !! 1/(1 + 2 gamma (cox + coy))
    integer :: jx, jy, x_loc, y_loc, i, iyoff, ic, iter, mxns, ns  !! mesh indices and locations, species index, offsets, iteration counter, row length and number of species
    ns   = w%ns
    mxns = w%mxns

    ! write matrix as P = D - L - U; load local arrays beta, beta2, gam,
    ! gam2, and cof1
    do i = 0, ns - 1
        temp     = 1.0_wp / (1.0_wp + 2.0_wp * gamma * (w%cox(i) + w%coy(i)))
        beta(i)  = gamma * w%cox(i) * temp
        beta2(i) = 2.0_wp * beta(i)
        gam(i)   = gamma * w%coy(i) * temp
        gam2(i)  = 2.0_wp * gam(i)
        cof1(i)  = temp
    end do

    ! begin iteration loop; load vector x with (D-inverse)*z for first iteration
    do jy = 0, MY - 1
        iyoff = mxns * jy
        do jx = 0, MX - 1
            ic = iyoff + ns * jx
            x(ic:ic+ns-1) = cof1 * z(ic:ic+ns-1)
        end do
    end do
    z(0:NEQ-1) = 0.0_wp

    ! looping point for iterations
    do iter = 1, ITMAX

        ! calculate (D-inverse)*U*x if not the first iteration
        if (iter > 1) then
            do jy = 0, MY - 1
                iyoff = mxns * jy
                do jx = 0, MX - 1  ! order of loops matters
                    ic    = iyoff + ns * jx
                    x_loc = 1; if (jx == 0) x_loc = 0; if (jx == MX - 1) x_loc = 2
                    y_loc = 1; if (jy == 0) y_loc = 0; if (jy == MY - 1) y_loc = 2
                    select case (3 * y_loc + x_loc)
                    case (0)  ! jx == 0, jy == 0
                        x(ic:ic+ns-1) = beta2 * x(ic+ns:ic+2*ns-1) + gam2 * x(ic+mxns:ic+mxns+ns-1)
                    case (1)  ! 1 <= jx <= mx-2, jy == 0
                        x(ic:ic+ns-1) = beta * x(ic+ns:ic+2*ns-1) + gam2 * x(ic+mxns:ic+mxns+ns-1)
                    case (2)  ! jx == mx-1, jy == 0
                        x(ic:ic+ns-1) = gam2 * x(ic+mxns:ic+mxns+ns-1)
                    case (3)  ! jx == 0, 1 <= jy <= my-2
                        x(ic:ic+ns-1) = beta2 * x(ic+ns:ic+2*ns-1) + gam * x(ic+mxns:ic+mxns+ns-1)
                    case (4)  ! 1 <= jx <= mx-2, 1 <= jy <= my-2
                        x(ic:ic+ns-1) = beta * x(ic+ns:ic+2*ns-1) + gam * x(ic+mxns:ic+mxns+ns-1)
                    case (5)  ! jx == mx-1, 1 <= jy <= my-2
                        x(ic:ic+ns-1) = gam * x(ic+mxns:ic+mxns+ns-1)
                    case (6)  ! jx == 0, jy == my-1
                        x(ic:ic+ns-1) = beta2 * x(ic+ns:ic+2*ns-1)
                    case (7)  ! 1 <= jx <= mx-2, jy == my-1
                        x(ic:ic+ns-1) = beta * x(ic+ns:ic+2*ns-1)
                    case (8)  ! jx == mx-1, jy == my-1
                        x(ic:ic+ns-1) = 0.0_wp
                    end select
                end do
            end do
        end if

        ! overwrite x with [(I - (D-inverse)*L)-inverse]*x
        do jy = 0, MY - 1
            iyoff = mxns * jy
            do jx = 0, MX - 1  ! order of loops matters
                ic    = iyoff + ns * jx
                x_loc = 1; if (jx == 0) x_loc = 0; if (jx == MX - 1) x_loc = 2
                y_loc = 1; if (jy == 0) y_loc = 0; if (jy == MY - 1) y_loc = 2
                select case (3 * y_loc + x_loc)
                case (0)  ! jx == 0, jy == 0
                case (1)  ! 1 <= jx <= mx-2, jy == 0
                    x(ic:ic+ns-1) = x(ic:ic+ns-1) + beta * x(ic-ns:ic-1)
                case (2)  ! jx == mx-1, jy == 0
                    x(ic:ic+ns-1) = x(ic:ic+ns-1) + beta2 * x(ic-ns:ic-1)
                case (3)  ! jx == 0, 1 <= jy <= my-2
                    x(ic:ic+ns-1) = x(ic:ic+ns-1) + gam * x(ic-mxns:ic-mxns+ns-1)
                case (4)  ! 1 <= jx <= mx-2, 1 <= jy <= my-2
                    x(ic:ic+ns-1) = x(ic:ic+ns-1) + beta * x(ic-ns:ic-1)
                    x(ic:ic+ns-1) = x(ic:ic+ns-1) + gam * x(ic-mxns:ic-mxns+ns-1)
                case (5)  ! jx == mx-1, 1 <= jy <= my-2
                    x(ic:ic+ns-1) = x(ic:ic+ns-1) + beta2 * x(ic-ns:ic-1)
                    x(ic:ic+ns-1) = x(ic:ic+ns-1) + gam * x(ic-mxns:ic-mxns+ns-1)
                case (6)  ! jx == 0, jy == my-1
                    x(ic:ic+ns-1) = x(ic:ic+ns-1) + gam2 * x(ic-mxns:ic-mxns+ns-1)
                case (7)  ! 1 <= jx <= mx-2, jy == my-1
                    x(ic:ic+ns-1) = x(ic:ic+ns-1) + beta * x(ic-ns:ic-1)
                    x(ic:ic+ns-1) = x(ic:ic+ns-1) + gam2 * x(ic-mxns:ic-mxns+ns-1)
                case (8)  ! jx == mx-1, jy == my-1
                    x(ic:ic+ns-1) = x(ic:ic+ns-1) + beta2 * x(ic-ns:ic-1)
                    x(ic:ic+ns-1) = x(ic:ic+ns-1) + gam2 * x(ic-mxns:ic-mxns+ns-1)
                end select
            end do
        end do

        ! add increment x to z : z <- z+x
        z(0:NEQ-1) = z(0:NEQ-1) + x(0:NEQ-1)

    end do
    end subroutine gs_iter

    end module cv_krylov_demo_prec_module
